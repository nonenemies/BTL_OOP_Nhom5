-- Sao lưu database trước khi chạy migration này.
-- Chuyển các trạng thái số hiện có: 1 -> HOAT_DONG, 0 -> NGUNG_HOAT_DONG.
ALTER TABLE Users MODIFY TrangThai VARCHAR(20) NULL DEFAULT NULL;
UPDATE Users
SET TrangThai = CASE
    WHEN TrangThai IS NULL OR TrangThai IN ('1', 'HOAT_DONG') THEN 'HOAT_DONG'
    WHEN TrangThai IN ('0', 'NGUNG_HOAT_DONG') THEN 'NGUNG_HOAT_DONG'
    ELSE NULL
END;
ALTER TABLE Users
    MODIFY TrangThai ENUM('HOAT_DONG', 'NGUNG_HOAT_DONG') NOT NULL DEFAULT 'HOAT_DONG';

